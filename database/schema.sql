-- 1. USERS

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT users_full_name_not_blank
        CHECK (LENGTH(TRIM(full_name)) > 0),

    CONSTRAINT users_email_not_blank
        CHECK (LENGTH(TRIM(email)) > 0),

    CONSTRAINT users_role_valid
        CHECK (role IN ('student', 'recruiter'))
);

-- Emails are unique regardless of capitalization.
CREATE UNIQUE INDEX users_email_lower_uq
    ON users (LOWER(email));


-- 2. COMPANIES

CREATE TABLE companies (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL UNIQUE,
    industry VARCHAR(100),
    city VARCHAR(100),
    website TEXT,
    description TEXT,

    CONSTRAINT companies_name_not_blank
        CHECK (LENGTH(TRIM(name)) > 0)
);


-- 3. SKILLS

CREATE TABLE skills (
    skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR(100) NOT NULL UNIQUE,
    category VARCHAR(80),

    CONSTRAINT skills_name_not_blank
        CHECK (LENGTH(TRIM(skill_name)) > 0)
);


-- 4. STUDENT PROFILES

CREATE TABLE student_profiles (
    student_id BIGINT PRIMARY KEY
        REFERENCES users(user_id) ON DELETE CASCADE,

    university VARCHAR(180),
    degree VARCHAR(120),
    graduation_year INTEGER,
    cgpa NUMERIC(4,2),
    city VARCHAR(100),
    phone VARCHAR(30),
    github_url TEXT,
    linkedin_url TEXT,
    portfolio_url TEXT,
    resume_url TEXT,
    bio TEXT,

    CONSTRAINT student_graduation_year_valid
        CHECK (
            graduation_year IS NULL
            OR graduation_year BETWEEN 2000 AND 2100
        ),

    CONSTRAINT student_cgpa_valid
        CHECK (cgpa IS NULL OR cgpa BETWEEN 0 AND 10)
);


-- 5. RECRUITER PROFILES

CREATE TABLE recruiter_profiles (
    recruiter_id BIGINT PRIMARY KEY
        REFERENCES users(user_id) ON DELETE CASCADE,

    company_id BIGINT
        REFERENCES companies(company_id) ON DELETE RESTRICT,

    job_title VARCHAR(120),

    CONSTRAINT recruiter_job_title_not_blank
        CHECK (
            job_title IS NULL
            OR LENGTH(TRIM(job_title)) > 0
        )
);


-- 6. INTERNSHIPS

CREATE TABLE internships (
    internship_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    company_id BIGINT NOT NULL
        REFERENCES companies(company_id) ON DELETE RESTRICT,

    posted_by BIGINT NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,

    title VARCHAR(180) NOT NULL,
    description TEXT NOT NULL,
    location VARCHAR(180),

    work_mode VARCHAR(20) NOT NULL,

    stipend_monthly NUMERIC(12,2),
    duration_months INTEGER NOT NULL,
    openings INTEGER NOT NULL DEFAULT 1,

    deadline DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'open',
    posted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT internships_title_not_blank
        CHECK (LENGTH(TRIM(title)) > 0),

    CONSTRAINT internships_description_not_blank
        CHECK (LENGTH(TRIM(description)) > 0),

    CONSTRAINT internships_work_mode_valid
        CHECK (work_mode IN ('remote', 'on_site', 'hybrid')),

    CONSTRAINT internships_stipend_nonnegative
        CHECK (
            stipend_monthly IS NULL
            OR stipend_monthly >= 0
        ),

    CONSTRAINT internships_duration_positive
        CHECK (duration_months > 0),

    CONSTRAINT internships_openings_positive
        CHECK (openings > 0),

    CONSTRAINT internships_status_valid
        CHECK (
            status IN (
                'draft',
                'open',
                'closed',
                'filled',
                'cancelled'
            )
        ),

    CONSTRAINT internships_deadline_valid
        CHECK (
            deadline IS NULL
            OR deadline >= posted_at::DATE
        )
);


-- 7. STUDENT SKILLS

CREATE TABLE student_skills (
    student_id BIGINT NOT NULL
        REFERENCES student_profiles(student_id) ON DELETE CASCADE,

    skill_id BIGINT NOT NULL
        REFERENCES skills(skill_id) ON DELETE CASCADE,

    proficiency VARCHAR(20) NOT NULL DEFAULT 'beginner',

    PRIMARY KEY (student_id, skill_id),

    CONSTRAINT student_skill_proficiency_valid
        CHECK (
            proficiency IN (
                'beginner',
                'intermediate',
                'advanced'
            )
        )
);


-- 8. INTERNSHIP SKILLS

CREATE TABLE internship_skills (
    internship_id BIGINT NOT NULL
        REFERENCES internships(internship_id) ON DELETE CASCADE,

    skill_id BIGINT NOT NULL
        REFERENCES skills(skill_id) ON DELETE CASCADE,

    PRIMARY KEY (internship_id, skill_id)
);


-- 9. SAVED INTERNSHIPS

CREATE TABLE saved_internships (
    student_id BIGINT NOT NULL
        REFERENCES student_profiles(student_id) ON DELETE CASCADE,

    internship_id BIGINT NOT NULL
        REFERENCES internships(internship_id) ON DELETE CASCADE,

    saved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (student_id, internship_id)
);


-- 10. APPLICATIONS

CREATE TABLE applications (
    application_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    internship_id BIGINT NOT NULL
        REFERENCES internships(internship_id) ON DELETE RESTRICT,

    student_id BIGINT NOT NULL
        REFERENCES student_profiles(student_id) ON DELETE RESTRICT,

    status VARCHAR(20) NOT NULL DEFAULT 'pending',

    status_changed_by BIGINT
       REFERENCES users(user_id) ON DELETE RESTRICT,

    cover_note TEXT,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- A student may apply to many internships and an internship may receive many applications
    -- But the same pair cannot occur twice
    CONSTRAINT applications_student_internship_uq
        UNIQUE (student_id, internship_id),

    CONSTRAINT applications_status_valid
        CHECK (
            status IN (
                'pending',
                'shortlisted',
                'rejected',
                'accepted',
                'withdrawn'
            )
        )
);


-- 11. APPLICATION STATUS HISTORY

CREATE TABLE application_status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    application_id BIGINT NOT NULL
        REFERENCES applications(application_id) ON DELETE CASCADE,

    old_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,

    changed_by BIGINT NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,

    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT history_old_status_valid
        CHECK (
            old_status IS NULL
            OR old_status IN (
                'pending',
                'shortlisted',
                'rejected',
                'accepted',
                'withdrawn'
            )
        ),

    CONSTRAINT history_new_status_valid
        CHECK (
            new_status IN (
                'pending',
                'shortlisted',
                'rejected',
                'accepted',
                'withdrawn'
            )
        ),

    CONSTRAINT history_status_must_change
        CHECK (
            old_status IS NULL
            OR old_status <> new_status
        )
);


-- 12. PROJECTS

CREATE TABLE projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    student_id BIGINT NOT NULL
        REFERENCES student_profiles(student_id) ON DELETE CASCADE,

    title VARCHAR(180) NOT NULL,
    description TEXT,
    project_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT projects_title_not_blank
        CHECK (LENGTH(TRIM(title)) > 0)
);


-- 13. INDEXES

CREATE INDEX internships_company_idx
    ON internships(company_id);

CREATE INDEX internships_posted_by_idx
    ON internships(posted_by);

CREATE INDEX internships_status_deadline_idx
    ON internships(status, deadline);

CREATE INDEX applications_student_applied_idx
    ON applications(student_id, applied_at DESC);

CREATE INDEX applications_internship_status_idx
    ON applications(internship_id, status);

CREATE INDEX status_history_application_changed_idx
    ON application_status_history(application_id, changed_at DESC);

CREATE INDEX projects_student_idx
    ON projects(student_id);

COMMIT;